#!/usr/bin/env python3
"""Writes THIRD_PARTY_NOTICES.txt (repository root) from the license files of the third-party code
Bluvu ships: the C++ libraries CMake fetches into the build folder and the editor's runtime npm
packages. Their licenses (MIT and similar) require these notices to go with every copy we hand out,
so the release bundle (docs/LICENSING_PLAN.md, phase 5) must include the file.

Run after a configure (cmake -B mosaic-engine/build) and `npm ci` in mosaic-engine/ui, and again
whenever a dependency's version changes:

    python3 mosaic-engine/tools/make_notices.py [--check]

--check fails if the committed file is out of date (or a license file is missing).
Not covered here, because it isn't open-source code: the NDI(R) SDK runtime, which is used under
Vizrt NDI AB's own license (see docs/THIRD_PARTY_LICENSES.md).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEPS = ROOT / "mosaic-engine" / "build" / "_deps"
UI = ROOT / "mosaic-engine" / "ui"
OUT = ROOT / "THIRD_PARTY_NOTICES.txt"


def cmake_version(name):
    """The pinned version from mosaic-engine/CMakeLists.txt (tag, release URL or commit)."""
    text = (ROOT / "mosaic-engine" / "CMakeLists.txt").read_text()
    block = re.search(r"FetchContent_Declare\(%s\b(.*?)\)" % re.escape(name), text, re.S)
    if not block:
        return "?"
    m = re.search(r"GIT_TAG\s+(\S+)", block.group(1)) or re.search(r"/download/(v[\d.]+)/", block.group(1))
    return m.group(1) if m else "?"


# (name, used for, where it comes from, license, license file)
CPP = [
    ("cpp-httplib", "the engine's web server and license-server client", "https://github.com/yhirose/cpp-httplib",
     "MIT", DEPS / "httplib-src" / "LICENSE", "httplib"),
    ("nlohmann/json", "JSON in the engine and receiver", "https://github.com/nlohmann/json",
     "MIT", DEPS / "nlohmann_json-src" / "LICENSE.MIT", "nlohmann_json"),
    ("stb (stb_image and others)", "loading pictures", "https://github.com/nothings/stb",
     "MIT or public domain (Unlicense), at our choice", DEPS / "stb-src" / "LICENSE", "stb"),
    ("Monocypher", "checking license-file signatures (Ed25519)", "https://github.com/LoupVaillant/Monocypher",
     "CC0-1.0 or BSD-2-Clause", DEPS / "monocypher-src" / "LICENCE.md", "monocypher"),
]

# The editor's runtime packages (what ends up in the built editor), from package-lock.json.
NPM_RUNTIME = ["react", "react-dom", "scheduler", "loose-envify", "js-tokens"]


def entries():
    problems = []
    out = []
    for name, use, url, lic, path, cmake_name in CPP:
        if not path.exists():
            problems.append(f"missing {path.relative_to(ROOT)} (configure the build first)")
            continue
        out.append((f"{name} {cmake_version(cmake_name)}", use, url, lic, path.read_text(errors="replace")))
    lock = json.loads((UI / "package-lock.json").read_text())["packages"]
    for pkg in NPM_RUNTIME:
        meta = lock.get(f"node_modules/{pkg}")
        if not meta or meta.get("dev"):
            problems.append(f"{pkg} isn't a runtime dependency in package-lock.json any more: update NPM_RUNTIME")
            continue
        path = UI / "node_modules" / pkg / "LICENSE"
        if not path.exists():
            problems.append(f"missing {path.relative_to(ROOT)} (run npm ci in mosaic-engine/ui)")
            continue
        out.append((f"{pkg} {meta['version']}", "the web editor", f"https://www.npmjs.com/package/{pkg}",
                    meta.get("license", "?"), path.read_text(errors="replace")))
    # Every runtime package in the lock file must be listed.
    for key, meta in lock.items():
        if key.startswith("node_modules/") and not meta.get("dev") and key.split("node_modules/")[-1] not in NPM_RUNTIME:
            problems.append(f"new runtime npm package {key}: add it to NPM_RUNTIME")
    return out, problems


def render(items):
    lines = [
        "Bluvu: third-party notices",
        "",
        "Bluvu is proprietary software of Blue Arc Networks (see LICENSE). It includes the open-source",
        "components below, each under its own license, reproduced here as those licenses require.",
        "",
        "Bluvu also uses the NDI(R) SDK runtime (Processing.NDI.Lib), under Vizrt NDI AB's NDI SDK license.",
        "NDI(R) is a registered trademark of Vizrt NDI AB. https://ndi.video/",
        "",
        "This file is generated by mosaic-engine/tools/make_notices.py; don't edit it by hand.",
        "",
    ]
    for title, use, url, lic, text in items:
        lines += ["=" * 100, f"{title}  ({lic})", f"Used for: {use}", url, "-" * 100, text.strip(), ""]
    return "\n".join(lines) + "\n"


def main():
    items, problems = entries()
    if problems:
        for p in problems:
            print("make_notices:", p, file=sys.stderr)
        sys.exit(1)
    text = render(items)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("make_notices: THIRD_PARTY_NOTICES.txt is out of date: run mosaic-engine/tools/make_notices.py", file=sys.stderr)
            sys.exit(1)
        print("make_notices: up to date")
        return
    OUT.write_text(text)
    print(f"make_notices: wrote {OUT.relative_to(ROOT)} ({len(items)} components)")


if __name__ == "__main__":
    main()
